import { stdin as processStdin, stdout as processStdout } from "node:process";
import { opaqueId, strictJsonClone } from "./canonical.mjs";
import { GuardianError, invariant } from "./errors.mjs";
import { PLAN_INTENT_SCHEMA } from "./intent-adapter.mjs";
import { MAX_PLAN_BYTES } from "./plan-store.mjs";

export const MAX_OBJECTIVE_BYTES = 16 * 1024;
export const MAX_PLANNER_RESPONSE_BYTES = MAX_PLAN_BYTES;
export const START_PRODUCER = "aio-start/0.2-d";

function deepFreeze(value) {
  if (value && typeof value === "object" && !Object.isFrozen(value)) {
    for (const child of Object.values(value)) deepFreeze(child);
    Object.freeze(value);
  }
  return value;
}

function clonePlannerResult(value) {
  let result;
  try {
    result = strictJsonClone(value, { code: "START_PLANNER_OUTPUT_INVALID", field: "Planner result" });
  } catch (error) {
    if (error instanceof GuardianError) throw error;
    throw new GuardianError(error?.code ?? "START_PLANNER_OUTPUT_INVALID", error?.message ?? "Planner result is invalid");
  }
  invariant(
    result && typeof result === "object" && !Array.isArray(result)
      && Object.keys(result).length === 1 && Object.hasOwn(result, "candidate_plan"),
    "START_PLANNER_OUTPUT_INVALID",
    "Planner result must contain exactly candidate_plan",
  );
  let bytes;
  try { bytes = Buffer.byteLength(JSON.stringify(result), "utf8"); }
  catch { throw new GuardianError("START_PLANNER_OUTPUT_INVALID", "Planner result is not serializable strict JSON"); }
  invariant(bytes <= MAX_PLANNER_RESPONSE_BYTES, "START_PLANNER_OUTPUT_TOO_LARGE", `Planner result exceeds ${MAX_PLANNER_RESPONSE_BYTES} bytes`);
  return deepFreeze(result);
}

export function validateObjective(value) {
  invariant(typeof value === "string" && value.trim().length > 0, "START_OBJECTIVE_INVALID", "aio start requires a non-empty objective");
  invariant(Buffer.byteLength(value, "utf8") <= MAX_OBJECTIVE_BYTES, "START_OBJECTIVE_TOO_LARGE", `Objective exceeds ${MAX_OBJECTIVE_BYTES} UTF-8 bytes`);
  return value;
}

export function observationBase(observation) {
  return Object.freeze({
    task_id: observation.task_id,
    plan_revision_id: observation.plan_revision_id,
    content_digest: observation.content_digest,
  });
}

/**
 * Minimal objective-to-plan orchestration. The injected planner receives an immutable
 * observation and has no PlanPort/writer capability. Authorization defaults to deny.
 */
export async function startPlanning(options) {
  const objective = validateObjective(options?.objective);
  const plan = options?.plan;
  const planner = options?.planner;
  invariant(plan && ["observe", "propose", "validate", "diff", "apply"].every((name) => typeof plan[name] === "function"), "START_PLAN_ADAPTER_INVALID", "A supported 0.2-C plan adapter is required");
  invariant(planner && typeof planner.plan === "function", "START_PLANNER_UNAVAILABLE", "No objective planner is configured");
  const authorize = options.authorize ?? (async () => false);
  const present = options.present ?? (() => {});
  invariant(typeof authorize === "function" && typeof present === "function", "START_AUTHORIZATION_INVALID", "Authorization and presentation boundaries must be callable");

  // This is the one and only observation for the attempt. Never re-observe or rebind.
  const observation = plan.observe();
  const plannerInput = deepFreeze(strictJsonClone({
    objective,
    observation: {
      schema: observation.schema,
      task_id: observation.task_id,
      plan_revision_id: observation.plan_revision_id,
      content_digest: observation.content_digest,
      plan: observation.plan,
    },
  }, { code: "START_PLANNER_INPUT_INVALID", field: "Planner input" }));

  const planned = clonePlannerResult(await planner.plan(plannerInput));
  const proposalId = (options.proposalIdFactory ?? (() => opaqueId("PPR-AIO-START")))();
  invariant(typeof proposalId === "string" && proposalId.length > 0 && proposalId.length <= 4096, "START_PROPOSAL_ID_INVALID", "Generated proposal_id is invalid");
  const proposal = plan.propose({
    schema: PLAN_INTENT_SCHEMA,
    proposal_id: proposalId,
    producer: START_PRODUCER,
    change_reason: "Plan candidate generated by aio start from a human objective.",
    base: observationBase(observation),
    candidate_plan: planned.candidate_plan,
  });
  const validation = plan.validate(proposal);
  const diff = plan.diff(proposal);
  const approvalContext = Object.freeze({ objective, observation, proposal, validation, diff });

  await present(approvalContext);
  const decision = await authorize(approvalContext);
  invariant(typeof decision === "boolean", "START_AUTHORIZATION_INVALID", "Authorization must return an explicit boolean decision");
  if (!decision) return Object.freeze({ status: "CANCELLED", objective, observation, proposal, validation, diff, applied: null });

  // Apply the exact frozen proposal shown above: no second planner call, ID, propose, or observe.
  const applied = plan.apply(proposal);
  return Object.freeze({ status: "APPLIED", objective, observation, proposal, validation, diff, applied });
}

function displayValue(value) {
  return JSON.stringify(value);
}

export function formatStartProposal({ objective, observation, proposal, diff }) {
  const lines = [
    "Objective:",
    `  ${displayValue(objective)}`,
    "",
    "Current plan:",
    `  ${observation.plan_revision_id}`,
    "",
    "Proposed plan:",
    `  ${proposal.proposed_plan_revision_id}`,
    `  proposal: ${proposal.proposal_id}`,
    `  digest: ${proposal.proposal_digest}`,
    "",
    "Changes:",
  ];
  let changes = 0;
  for (const entry of diff.plan.added) { lines.push(`  + plan[${displayValue(entry.field)}] = ${displayValue(entry.value)}`); changes += 1; }
  for (const entry of diff.plan.removed) { lines.push(`  - plan[${displayValue(entry.field)}] = ${displayValue(entry.value)}`); changes += 1; }
  for (const entry of diff.plan.changed) { lines.push(`  ~ plan[${displayValue(entry.field)}]: ${displayValue(entry.before)} -> ${displayValue(entry.after)}`); changes += 1; }
  for (const entry of diff.task_items.added) { lines.push(`  + item ${displayValue(entry.task_item_id)}: ${displayValue(entry.value)}`); changes += 1; }
  for (const entry of diff.task_items.removed) { lines.push(`  - item ${displayValue(entry.task_item_id)}: ${displayValue(entry.value)}`); changes += 1; }
  for (const entry of diff.task_items.changed) {
    for (const field of entry.fields.added) { lines.push(`  + item ${displayValue(entry.task_item_id)}[${displayValue(field.field)}] = ${displayValue(field.value)}`); changes += 1; }
    for (const field of entry.fields.removed) { lines.push(`  - item ${displayValue(entry.task_item_id)}[${displayValue(field.field)}] = ${displayValue(field.value)}`); changes += 1; }
    for (const field of entry.fields.changed) { lines.push(`  ~ item ${displayValue(entry.task_item_id)}[${displayValue(field.field)}]: ${displayValue(field.before)} -> ${displayValue(field.after)}`); changes += 1; }
  }
  if (changes === 0) lines.push("  none");
  return lines.join("\n");
}

export function formatStartResult(result) {
  if (result.status === "CANCELLED") return "Plan not applied.";
  return [
    "Plan applied:",
    `  ${result.applied.plan_revision_id}`,
    `Proposal ID: ${result.applied.proposal_id}`,
    "Next: review TASK_PLAN.md; implementation has not been started.",
  ].join("\n");
}

export function createStdinAuthorizer(options = {}) {
  const input = options.input ?? processStdin;
  const output = options.output ?? processStdout;
  return async () => {
    try {
      output.write("Apply this plan? [y/N] ");
      let answer = "";
      for await (const chunk of input) {
        answer += Buffer.isBuffer(chunk) ? chunk.toString("utf8") : String(chunk);
        if (answer.length > 1024) return false;
        const newline = answer.search(/[\r\n]/);
        if (newline >= 0) { answer = answer.slice(0, newline); break; }
      }
      return /^(?:y|yes)$/i.test(answer.trim());
    } catch {
      return false;
    }
  };
}
